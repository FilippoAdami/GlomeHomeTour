import torch
import torch.nn.functional as F
from torch.autograd import Variable
from math import exp

def l1_loss(network_output, gt):
    return torch.abs((network_output - gt)).mean()

def l2_loss(network_output, gt):
    return ((network_output - gt) ** 2).mean()

def compute_saturation_mask(img, min_threshold=0.98, percentile=99.8, max_chroma_diff=0.15):
    """Compute dynamic saturation mask for a (C, H, W) PyTorch float tensor in [0, 1].

    Returns a boolean tensor of shape (H, W) where True indicates saturated/bloom pixels.
    """
    if img.numel() == 0:
        return torch.zeros(img.shape[-2:], dtype=torch.bool, device=img.device)

    max_ch = img.max(dim=0).values
    min_ch = img.min(dim=0).values
    frame_max = max_ch.max().item()
    if frame_max < min_threshold:
        return torch.zeros(img.shape[-2:], dtype=torch.bool, device=img.device)

    q = float(torch.quantile(max_ch.float(), percentile / 100.0).item())
    t_dyn = float(max(min_threshold, min(0.995, q)))

    chroma_diff = max_ch - min_ch
    is_sat = (max_ch >= t_dyn) & (chroma_diff <= max_chroma_diff)
    return is_sat

def masked_l1_loss(network_output, gt, mask=None):
    """L1 loss computed only on valid (unmasked) pixels where mask == True."""
    diff = torch.abs(network_output - gt)
    if mask is None:
        return diff.mean()
    if mask.dim() == 2:
        mask = mask.unsqueeze(0)
    if mask.shape[0] == 1 and diff.shape[0] == diff.size(-3):
        mask = mask.expand(diff.size(-3), -1, -1)
    denom = mask.sum().clamp_min(1.0)
    return (diff * mask).sum() / denom

def gaussian(window_size, sigma):
    gauss = torch.Tensor([exp(-(x - window_size // 2) ** 2 / float(2 * sigma ** 2)) for x in range(window_size)])
    return gauss / gauss.sum()


def smooth_loss(disp, img):
    grad_disp_x = torch.abs(disp[:,1:-1, :-2] + disp[:,1:-1,2:] - 2 * disp[:,1:-1,1:-1])
    grad_disp_y = torch.abs(disp[:,:-2, 1:-1] + disp[:,2:,1:-1] - 2 * disp[:,1:-1,1:-1])
    grad_img_x = torch.mean(torch.abs(img[:, 1:-1, :-2] - img[:, 1:-1, 2:]), 0, keepdim=True) * 0.5
    grad_img_y = torch.mean(torch.abs(img[:, :-2, 1:-1] - img[:, 2:, 1:-1]), 0, keepdim=True) * 0.5
    grad_disp_x *= torch.exp(-grad_img_x)
    grad_disp_y *= torch.exp(-grad_img_y)
    return grad_disp_x.mean() + grad_disp_y.mean()

def create_window(window_size, channel):
    _1D_window = gaussian(window_size, 1.5).unsqueeze(1)
    _2D_window = _1D_window.mm(_1D_window.t()).float().unsqueeze(0).unsqueeze(0)
    window = Variable(_2D_window.expand(channel, 1, window_size, window_size).contiguous())
    return window

def ssim(img1, img2, window_size=11, size_average=True):
    channel = img1.size(-3)
    window = create_window(window_size, channel)

    if img1.is_cuda:
        window = window.cuda(img1.get_device())
    window = window.type_as(img1)

    return _ssim(img1, img2, window, window_size, channel, size_average)

def _ssim(img1, img2, window, window_size, channel, size_average=True):
    mu1 = F.conv2d(img1, window, padding=window_size // 2, groups=channel)
    mu2 = F.conv2d(img2, window, padding=window_size // 2, groups=channel)

    mu1_sq = mu1.pow(2)
    mu2_sq = mu2.pow(2)
    mu1_mu2 = mu1 * mu2

    sigma1_sq = F.conv2d(img1 * img1, window, padding=window_size // 2, groups=channel) - mu1_sq
    sigma2_sq = F.conv2d(img2 * img2, window, padding=window_size // 2, groups=channel) - mu2_sq
    sigma12 = F.conv2d(img1 * img2, window, padding=window_size // 2, groups=channel) - mu1_mu2

    C1 = 0.01 ** 2
    C2 = 0.03 ** 2

    ssim_map = ((2 * mu1_mu2 + C1) * (2 * sigma12 + C2)) / ((mu1_sq + mu2_sq + C1) * (sigma1_sq + sigma2_sq + C2))

    if size_average:
        return ssim_map.mean()
    else:
        return ssim_map.mean(1).mean(1).mean(1)

def masked_ssim(img1, img2, mask=None, window_size=11):
    """Compute SSIM weighted by valid (unmasked) pixel mask."""
    channel = img1.size(-3)
    window = create_window(window_size, channel)

    if img1.is_cuda:
        window = window.cuda(img1.get_device())
    window = window.type_as(img1)

    mu1 = F.conv2d(img1, window, padding=window_size // 2, groups=channel)
    mu2 = F.conv2d(img2, window, padding=window_size // 2, groups=channel)

    mu1_sq = mu1.pow(2)
    mu2_sq = mu2.pow(2)
    mu1_mu2 = mu1 * mu2

    sigma1_sq = F.conv2d(img1 * img1, window, padding=window_size // 2, groups=channel) - mu1_sq
    sigma2_sq = F.conv2d(img2 * img2, window, padding=window_size // 2, groups=channel) - mu2_sq
    sigma12 = F.conv2d(img1 * img2, window, padding=window_size // 2, groups=channel) - mu1_mu2

    C1 = 0.01 ** 2
    C2 = 0.03 ** 2

    ssim_map = ((2 * mu1_mu2 + C1) * (2 * sigma12 + C2)) / ((mu1_sq + mu2_sq + C1) * (sigma1_sq + sigma2_sq + C2))

    if mask is None:
        return ssim_map.mean()

    if mask.dim() == 2:
        mask = mask.unsqueeze(0)
    if mask.shape[0] == 1 and ssim_map.shape[0] == channel:
        mask = mask.expand(channel, -1, -1)
    denom = mask.sum().clamp_min(1.0)
    return (ssim_map * mask).sum() / denom

