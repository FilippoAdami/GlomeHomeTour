import importlib
import torch

__attributes = {
    # Sparse Structure
    'SparseStructureEncoder': 'sparse_structure_vae',
    'SparseStructureDecoder': 'sparse_structure_vae',
    'SparseStructureFlowModel': 'sparse_structure_flow',
    
    # SLat Generation
    'SLatFlowModel': 'structured_latent_flow',
    'ElasticSLatFlowModel': 'structured_latent_flow',
    
    # SC-VAEs
    'SparseUnetVaeEncoder': 'sc_vaes.sparse_unet_vae',
    'SparseUnetVaeDecoder': 'sc_vaes.sparse_unet_vae',
    'FlexiDualGridVaeEncoder': 'sc_vaes.fdg_vae',
    'FlexiDualGridVaeDecoder': 'sc_vaes.fdg_vae'
}

__submodules = []

__all__ = list(__attributes.keys()) + __submodules

def __getattr__(name):
    if name not in globals():
        if name in __attributes:
            module_name = __attributes[name]
            module = importlib.import_module(f".{module_name}", __name__)
            globals()[name] = getattr(module, name)
        elif name in __submodules:
            module = importlib.import_module(f".{name}", __name__)
            globals()[name] = module
        else:
            raise AttributeError(f"module {__name__} has no attribute {name}")
    return globals()[name]


def from_pretrained(path: str, *, load_on_meta: bool = False, **kwargs):
    """
    Load a model from a pretrained checkpoint.

    Args:
        path: The path to the checkpoint. Can be either local path or a Hugging Face model name.
              NOTE: config file and model file should take the name f'{path}.json' and f'{path}.safetensors' respectively.
        load_on_meta: Assign checkpoint tensors without initializing model weights first.
        **kwargs: Additional arguments for the model constructor.
    """
    import os
    import json
    from safetensors.torch import load_file
    is_local = os.path.exists(f"{path}.json") and os.path.exists(f"{path}.safetensors")

    if is_local:
        config_file = f"{path}.json"
        model_file = f"{path}.safetensors"
    else:
        from huggingface_hub import hf_hub_download
        path_parts = path.split('/')
        repo_id = f'{path_parts[0]}/{path_parts[1]}'
        model_name = '/'.join(path_parts[2:])
        config_file = hf_hub_download(repo_id, f"{model_name}.json")
        model_file = hf_hub_download(repo_id, f"{model_name}.safetensors")

    with open(config_file, 'r') as f:
        config = json.load(f)
    model_class = __getattr__(config['name'])
    state = load_file(model_file)
    if load_on_meta:
        with torch.device('meta'):
            model = model_class(**config['args'], **kwargs)
        expected = model.state_dict()
        # assign=True skips the dtype cast performed by ordinary load_state_dict.
        assigned = {
            name: tensor.to(dtype=expected[name].dtype) if name in expected else tensor
            for name, tensor in state.items()
        }
        result = model.load_state_dict(assigned, strict=False, assign=True)
        missing = set(result.missing_keys)
        if missing == {'rope_phases'} and hasattr(model, '_make_rope_phases'):
            model.rope_phases = model._make_rope_phases(torch.device('cpu'))
            missing.clear()
        has_meta = any(t.is_meta for t in model.buffers()) or any(
            isinstance(value, torch.Tensor) and value.is_meta
            for module in model.modules() for value in vars(module).values()
        )
        if not missing and not has_meta:
            return model
    model = model_class(**config['args'], **kwargs)
    model.load_state_dict(state, strict=False)

    return model


